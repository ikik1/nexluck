"""Build the synchronous browser catalog from the editable UI JSON catalogs."""
import json
import re
from collections import Counter
from pathlib import Path

DIRECTORY = Path(__file__).resolve().parent
LANGUAGES = ("en", "ru", "pt-PT", "pt-BR", "es")


def unique_object(pairs):
    result = {}
    for key, value in pairs:
        if key in result:
            raise ValueError(f"Duplicate translation key: {key!r}")
        result[key] = value
    return result


def render():
    messages = {language: {} for language in LANGUAGES}
    for path in sorted(DIRECTORY.glob("*.json")):
        catalog = json.loads(path.read_text(), object_pairs_hook=unique_object)
        if set(catalog) != set(LANGUAGES) or any(
            entries.keys() != catalog["en"].keys() for entries in catalog.values()
        ):
            raise ValueError(f"{path.name}: all supported languages must contain the same keys")
        for language, entries in catalog.items():
            for key, value in entries.items():
                if not isinstance(key, str) or not isinstance(value, str) or not value:
                    raise ValueError(f"{path.name}: nonempty text translations required")
                if language == "en" and key != value:
                    raise ValueError(f"{path.name}: English sources must match their keys")
                if Counter(re.findall(r"\{\w+\}", key)) != Counter(re.findall(r"\{\w+\}", value)):
                    raise ValueError(f"{path.name}: interpolation placeholders differ for {key!r}")
                previous = messages[language].get(key)
                if previous is not None and previous != value:
                    raise ValueError(f"{path.name}: conflicting translation for {key!r}")
                messages[language][key] = value
    serialized = json.dumps(messages, ensure_ascii=False, sort_keys=True, indent=2)
    return (
        "// Generated by localization/build_catalog.py; edit the JSON catalogs instead.\n"
        "window.NexLuckMessages = " + serialized + ";\n"
    )


def build():
    (DIRECTORY / "catalog.js").write_text(render())


if __name__ == "__main__":
    build()
